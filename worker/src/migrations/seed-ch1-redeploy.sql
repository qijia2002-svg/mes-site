> 本章用一个真实例子带你走一遍：一张工单从「客户下单」到「关单结算」会经历什么。读完你能指着一张工单说出它现在在哪一步、为什么卡住、下一步该干什么。

## 先认识一张真实的工单

打开系统，找一张生产工单，比如 **WO-20260801-02**。它在样例库里的真实数据是：

- 要生产什么：某型号产品，计划 **60 台**
- 归属车间：二号车间
- 交期：2026-08-12
- 现在状态：`running`（生产中，已报工 40 / 60 台）

工单（Work Order，现场常简称 **WO**）就是 MES 里这张「派工单」。它把 ERP 那句「计划要生产什么」，落成车间里「谁、在哪台设备、什么时候、做多少」的具体指令。后面所有现场问题的排查，最后都会回到某一张工单上。

## 工单从哪来

典型的来源有三条：

1. **ERP 计划下发**：ERP 跑完 MRP 运算，生成生产计划，通过接口把工单推给 MES。这是大多数工厂的主路径。
2. **MES 内部排产**：MES 自带排产模块，按设备产能和交期自动拆单。
3. **人工补单**：现场临时插单、返工单，由计划员手工新建。

> 留意第三条。人工补单往往没有 ERP 的单号规则约束，是后期对账对不上的高发区——这也是系统要管住「谁能建单」的原因。

## 工单会经历哪几个状态

工单状态机是 MES 的骨架，不同厂商叫法略不同，但语义一致：

| 状态 | 含义 | 车间里这一步在干什么 |
|---|---|---|
| `created` | 已创建 | 计划员刚建单，还没下发车间 |
| `released` | 已下达 | 已下发，可以领料、可以开工 |
| `running` | 生产中 | 已有第一次报工，工单进入在制状态 |
| `finished` | 已完工 | 产出数量达标，停止报工 |
| `closed` | 已关闭 | 成本归集、库存入账，财务口径锁定 |

以 WO-20260801-02 为例，它现在 `running`、已报工 40/60 台，正处在「生产中」这一步。带着它去工厂全景点一遍「客户下单 → 生产工单」，比读十遍都管用。

## 状态不能乱跳：三条铁律

**第一，状态只能单向前进。** 不允许从 `running` 退回 `released`。现场要撤销，走「作废重开」而不是「状态回退」——否则已经产生的报工记录会变成对不上的孤儿数据。

**第二，`finished` 与 `closed` 必须分开。** 很多新人会问：完工了直接关掉不就行了？不行。完工是**生产口径**（车间干完了）；关闭是**财务口径**（成本已归集、库存已入账），中间往往隔着几天对账期。把两个状态合并，是后期成本核算算不准的典型根因。

**第三，只有 `released` 之后才允许领料和报工。** 这是权限校验的关键卡点。如果发现现场能对一张 `created` 状态的工单报工，那一定是状态校验被绕过了，属于严重缺陷。

## 出问题时先看哪三个字段

接到「这张工单不对」的报障，先查三个字段：`state`（当前状态）、`plan_qty`（计划数量）、`done_qty`（已完成数量）。它们的组合能立刻暴露问题类型：

- `state = ''running''` 但 `done_qty = 0`：状态被误置，或报工接口失败
- `done_qty > plan_qty`：超产未管控，需检查报工时的数量校验
- `state = ''finished''` 但 `done_qty < plan_qty`：欠产完工，通常需确认是否走了审批

拿 WO-20260801-02 对照看：它 `state=running`、`done_qty=40`、`plan_qty=60`，属于正常的在制；一旦某天它变成 `finished` 却仍只有 40 台，就触发上面第三条异常。

## 小结 & 下一步

- 工单是 MES 把「计划」落成「车间动作」的那张单。
- 五个状态单向前进，`finished` 和 `closed` 别混。
- 排查先抓 `state / plan_qty / done_qty` 三个字段。

下一站去「工单主表结构与高频查询」，你会看到这些状态、数量在数据库里到底存在哪几列。

