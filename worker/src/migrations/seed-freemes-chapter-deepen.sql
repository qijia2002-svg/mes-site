## 真实 MES 怎么落地报工（参考 free-mes 开源实现）

开源真 MES（free-mes）的报工不是"一张表记完"，而是**三张表联动**：

- `WorkOrder`（工单）→ `Task`（按工序拆的执行单元，状态 NoSTARTED）→ `Feedback`（一次报工）。
- 报工 `Feedback` 记的是：任务、工序、工位、**设备**、操作人、报工数量、起止时间。
