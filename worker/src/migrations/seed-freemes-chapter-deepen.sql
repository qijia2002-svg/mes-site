## 真实 MES 的完整报工链路（参考 free-mes 开源实现）

本章讲的是平台简化模型（报工→qty_done 累加）。真实开源 MES 的链路更细，是**三张表逐级下发**：

1. `WorkOrder`（工单）下发成多个 `Task`——每个 Task 是**一道工序**的执行单元，绑工位、绑设备、绑班组，初始状态 `NoSTARTED`。
