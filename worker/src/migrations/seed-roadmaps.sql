### 第一步：读懂行业的"黑话"（术语）

每个行业都有自己的语言。以下是汽车零部件行业的例子：

| 术语 | 含义 |
|------|------|
| MES | 制造执行系统 |
| BOM | 物料清单 |
| 工序报工 | 工人在每道工序完成后向系统汇报 |
| SPC | 统计过程控制 |
| OEE | 设备综合效率 |
| 批次追溯 | 知道这个零件是哪天、哪台设备、哪个班次做的 |
| 良品率 | 合格品数量 / 总产出数量 |
| 工时定额 | 完成一道工序的标准时间 |
| 工艺路线 | 一个产品要经过哪些工序，每道工序用什么设备 |

**你的行业术语清单**：去招聘 JD 或行业文章里找，整理 20 个专业术语，附上解释。

### 第二步：理解核心业务流

以汽车零部件行业为例，理解这条主流程：

```
销售订单（客户要货）→ 生产计划（排产）→ 工单下达（具体任务）→ 
工序执行（车间生产）→ 质量检测（每个环节）→ 完工入库→ 发货
```

每个环节的数据：
- 销售订单：订单号、数量、交期、客户规格
- 生产计划：排产依据、优先级
- 工单：产品型号、数量、工序列表
- 工序执行：谁做的、花了多久、产出多少
- 质量检测：检测数据、不良品数量
- 入库/发货：批次号、物流信息

### 第三步：找到行业的"高频痛苦"

每个行业的痛点不同。以下是汽车零部件行业的高频痛点：

**痛点1：追溯难**
- 问题：出了质量问题，要从成品一步步追溯到原材料，需要几天
- 系统能解决什么：扫码报工 + 批次号 → 5分钟内查到完整追溯链

**痛点2：设备 OEE 看不见**
- 问题：产能利用率全靠经验估计，不知道哪里有损失
- 系统能解决什么：实时采集设备运行数据 → OEE 看板 → 定位瓶颈工序

**痛点3：计划排产靠经验**
- 问题：换线频繁，插单多，全靠计划员经验
- 系统能解决什么：APS 高级计划排程 → 自动优化排产方案

