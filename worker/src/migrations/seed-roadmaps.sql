场景3：发现数据异常
```sql
-- 找出重复录入的物料编码
SELECT material_code, COUNT(*) as cnt
FROM material_master
GROUP BY material_code
HAVING cnt > 1;
```

### 面试常问的 SQL 问题

1. "SQL 中 WHERE 和 HAVING 的区别？" → WHERE过滤行，HAVING过滤分组后的结果
2. "LEFT JOIN 和 INNER JOIN 的区别？" → LEFT JOIN保留左表全部记录，INNER JOIN只保留两边都有的
3. "如何找出某个字段重复的记录？" → GROUP BY + HAVING COUNT(*) > 1
4. "MySQL 和 Oracle 的区别？" → 实施工程师了解差异即可，不用深入（Oracle收费，MySQL免费开源，语法略有差异）

