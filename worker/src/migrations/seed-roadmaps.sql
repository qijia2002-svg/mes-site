## 各步骤详细说明

### Step 1：需求调研（最关键的一步）

**错误的做法**：
- 直接问"你们想要什么功能"
- 只和 IT 负责人聊，不和生产一线聊
- 把客户说的全部记下来，不做分析

**正确的做法**：
- 问业务不问系统："你们现在生产计划的频率是多久？调整频率呢？"
- 看数据不看方案：调出实际工单数据、库存数据，观察真实的流转
- 多层级访谈：生产经理（一线操作工 / 车间主任 / IT负责人 / 高管）

**需求调研三神器**：
1. **现状流程图**（AS-IS）：画出现在的流程，不评价对错，只记录
2. **痛点访谈**：用"五个为什么"挖根因
3. **数据抽样**：从系统导出真实数据，和访谈内容交叉验证

---

### Step 2：方案设计

**方案设计的核心原则**：
- **方案要分层次**：现状问题 → 解决思路 → 功能设计 → 预期效果
- **不要过度设计**：先满足核心需求，再考虑高级功能
- **和客户对齐**：方案做完了，先和关键用户对齐，再进入配置

**方案文档结构**：
```
一、项目背景与目标
二、现状问题分析
三、解决方案（分模块描述）
  - 模块1：XXX
 - 功能点1
 - 功能点2
四、预期效果（量化）
五、实施计划
六、风险评估
```

---

### Step 3：系统配置

**配置五原则**：
1. 先基础数据，后业务功能
2. 先主流程，后异常流程
3. 配完一个模块验证一个模块，不要全部配完再测
4. 配置过程记录文档，方便回溯
5. 上线前做数据清洗，避免垃圾进垃圾出

**常见配置模块**：
- 基础数据：组织架构、工厂/车间/产线、物料编码体系、BOM
- 生产管理：工单类型、工单状态流转、工序定义
- 质量管理：质检方案、不良品处理流程
- 设备管理：设备台账、点检计划、OEE 计算

---

### Step 4：测试验证（UAT）

**UAT 和 SIT 的区别**：
- SIT（系统集成测试）：技术团队做的内部测试
- UAT（用户验收测试）：让真实用户来测，确认系统满足业务需求

**UAT 核心原则**：
- 测试用例由业务用户编写或审核，不是实施工程师自己写
- 测试结果要记录，不仅仅是"测过了"
- 发现的 bug 要分级（P1/P2/P3），决定是否影响上线

---

### Step 5：上线切换

**上线三件套**：
1. **数据迁移**：旧系统数据 → 新系统，要做映射和清洗
2. **并行运行**：新系统上线后和旧系统并行一段时间（1-2周）
3. **用户培训**：分角色培训（操作员重操作，管理员重配置）

**上线风险预案**：
- 回滚方案：上线失败了怎么退回旧系统？
- 数据修复方案：上线后发现数据问题怎么办？
- 用户支持方案：上线第一周要安排专人驻场支持

---

### Step 6：验收交付

**验收的关键**：
- 验收标准在合同里就要约定清楚，不能到验收了才说"我们觉得应该这样"
- 项目总结要客观：哪里做得好，哪里没做到，下次怎么改
- 文档移交要完整：系统配置文档、培训材料、运维手册

