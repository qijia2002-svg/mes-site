### 类型二：技术基础类（会问但不深）

**Q4："Modbus RTU和Modbus TCP的区别？"**

> "Modbus RTU走RS485总线，用A/B两根线，最远能传1200米，适合近距离工业现场。Modbus TCP走网线，基于TCP/IP协议，可以远距离传输，也可以和IT网络融合。我现场见过两种都有，根据现场布线条件选择。"

**Q5："西门子PLC和三菱PLC有什么区别？"**

> "西门子PLC（TIA Portal）在大型工厂用得最多，性能强，编程复杂；三菱PLC在中小型设备上常见，上手相对简单。我现场接触过两种品牌，主要工作是配合PLC维护人员调试点位，不深入编程。"

**Q6："你了解哪些工业通讯协议？"**

把你知道的都说出来：Modbus RTU、Modbus TCP、OPC UA、Profinet、Ethernet/IP。

