## 重点知识：PLC基础（面试要能讲5分钟）

### PLC是什么
> PLC（可编程逻辑控制器）：安装在工厂现场的"工业大脑"，负责接收传感器信号、执行控制逻辑、输出控制信号给执行器。

### 你接触过的PLC
- **西门子PLC**：德国品牌，工业领域最常见，编程软件是TIA Portal
- **三菱PLC**：日本品牌，在小型设备上用得多

### SCADA和PLC的关系
```
传感器信号 → PLC（执行控制逻辑） → 采集模块（SCADA） → 大屏显示
 ↑ ↓
 ←←←←←←←←← 控制指令 ←←←←←←←←←←←←←←←
```

### 面试能讲的PLC理解
> "PLC是现场的控制器，负责执行具体的控制逻辑。
> SCADA不直接控制设备，而是通过和PLC通讯来获取数据和下发指令。
> 我在现场见过西门子PLC和三菱PLC，知道PLC的基本输入输出逻辑，
