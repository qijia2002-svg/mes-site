> "我会分两层排查。第一层是数据链路：从设备传感器开始，看PLC是否有正确采集，然后看SCADA采集模块是否正常，最后看数据库里的值对不对。第二层是业务逻辑：如果数据链路没问题，就看是不是MES系统里的配置错了，比如BOM版本不对或者工序状态流转有问题。最常用的工具是SQL查询和SCADA日志。"

