## 面试高频问题库（按类型分类）

### 背景类（必问）

**Q1："请做一个自我介绍"**
> 控制在2分钟内，结构：
> 1. 我是谁 + 背景（1句）
> 2. 我的核心能力（2-3句，每句一个能力+例子）
> 3. 我为什么来应聘这个岗位（1句）

**Q2："你为什么从现在的公司离职/想转行？"**
> 禁忌：抱怨前公司/前领导/工资低
> 正确：聚焦未来（我想做实施、我看好这个方向、我的背景适合）

**Q3："你对我们公司了解多少？"**
> 禁忌：说"不太了解"
> 正确：提前查公司官网/产品/行业，至少说出3点

---

### 技术类（会问但不深）

**Q4："你熟悉哪些数据库？"**
> 重点：展示SQL实战经验，不要只说"熟悉MySQL"
> 正确："主要用MySQL，能独立写SELECT/JOIN/聚合查询，之前用SQL排查过MES数据准确性问题"

**Q5："你了解MES系统的哪些模块？"**
> 重点：说出你用过的模块 + 知道其他模块是干什么的
> 正确："用过生产管理（工单/报工/工序）、质量模块（质检/不良品）；了解设备管理（OEE）和物料管理（BOM）"

**Q6："Linux会多少？"**
> 重点：能说清楚实际用过哪些
> 正确："能在Linux上查日志、改权限、重启服务。排查过Tomcat内存溢出问题"

---

### 业务类（拉开差距的关键）

**Q7："你对我们这个行业有什么了解？"**
> 这是本周重点准备的内容
> 结构：行业特点 → 核心痛点 → 我的理解

**Q8："如果客户说''系统太复杂了，我们不会用''，你怎么处理？"**
> 重点：不是反驳，是理解+解决
> 参考："我会先了解用户是哪个角色、觉得哪部分复杂，然后分角色、分场景做培训，而不是一次性讲所有功能"

**Q9："你做过的最有成就感的一个项目是什么？"**
> 重点：STAR法则 + 量化结果
> 禁忌：说"没什么特别的项目"——任何经历都能包装

