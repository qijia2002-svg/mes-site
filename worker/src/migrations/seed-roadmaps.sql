- 质量追溯链路：物料批号 + 生产批次 + 设备 + 操作人员

### 模块3：设备管理（台账 + 维护 + OEE）
设备是 MES 数据的重要来源。实施工程师要掌握：
- 设备台账（基本信息 + 动态数据：运行时间/维护记录/故障记录）
- 设备分类（生产类/仪器类/辅助类/工具类/运输类）
- 维护计划（定期保养/故障维修/OEE计算）
- 设备与 MES 的数据交互（OPCUA / MQTT / API）

### 模块4：物料与仓库管理
MES 的物料管理和 ERP 不同，更关注：
- 线边仓管理（工序间的物料流转）
- 物料追溯（批次追溯）
- BOM 在 MES 中的作用（和 ERP BOM 的区别）
- 来料检验 → 库存 → 领料 → 工序 → 成品 的完整流转

