## 重点知识：Modbus协议（你简历提了，必须能讲）

### Modbus一句话本质
> Modbus是一种**工业设备之间对话的语言**，定义了"谁来问、问什么、怎么答"的规则。

### 你实际接触过的Modbus场景
```
设备（变频器/电表） ←Modbus RTU/TCP→ SCADA采集模块 ←→ 大屏显示
```

### Modbus两种常见形式
- **Modbus RTU**：通过RS485总线传输，最常见，接线是A/B两根线
- **Modbus TCP**：通过网线传输，基于TCP/IP协议

### 面试能讲清楚的"掉线问题排查思路"
> "设备掉线了，我一般先看SCADA软件里这个设备的状态，
