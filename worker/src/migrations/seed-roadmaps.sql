## 两大决胜绝招

### 绝招一：沟通表达力（隐形王牌）

面试不是考试，是**销售**——你在向客户（公司）销售你的能力。

**STAR法则（所有回答的万能模板）**：

| 维度 | 含义 | 回答示例 |
|------|------|----------|
| **S - Situation** | 情境：当时的情况是什么？ | "当时客户工厂刚上线新产线，发现MES工单数据大量报错" |
| **T - Task** | 任务：你的职责是什么？ | "我作为实施工程师，负责排查数据问题" |
| **A - Action** | 行动：你具体做了什么？ | "我用SQL查询了工单表和报工表的关联数据，发现是BOM版本号不一致导致的" |
| **R - Result** | 结果：最终效果是什么？ | "修复后数据准确率达到99.5%，客户满意度大幅提升" |

**STAR法则使用原则**：
- 80%内容放在 A（行动），40%在 R（结果）
- 结果要量化（减少多少时间/提升多少效率/节省多少成本）
- 不好的结果也可以说，但重点是你从中学到了什么

---

### 绝招二：业务理解力（拉开差距的关键）

**面试的本质问题只有一个**：你能不能帮客户解决问题？

体现方式：
- 锁定一个行业（这周继续强化）
- 能说出该行业的核心痛点和系统解决方案
- 能用"客户视角"回答问题，不只是背功能

**客户视角 vs 技术视角对比**：

| 问题 | 技术视角（错） | 客户视角（对） |
|------|---------------|---------------|
| "你做过什么？" | "我配置了MES系统" | "我帮XX车间把排产时间从3小时缩短到20分钟" |
| "你会什么？" | "我会SQL、Linux" | "我能独立排查数据问题，帮客户验证上线数据准确性" |
| "你的优势？" | "我学得快" | "我既懂系统配置，又能站在客户业务角度设计方案" |

