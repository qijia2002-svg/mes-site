## 模块C：沟通软技能

**实施工程师的沟通场景**：
- 需求调研：和客户业务人员开会，挖掘真实需求（不是他们说的表面需求）
- 方案汇报：向客户管理层解释系统设计
- 冲突处理：客户需求变更，实施顾问夹在客户和开发之间
- 用户培训：把复杂操作讲得让老工人能听懂

**沟通三原则**：
1. **说对方听得懂的话**：技术人员讲 API/数据库，业务人员讲 KPI/订单量/良品率
2. **先讲结论，再说原因**：金字塔原理，电梯演讲法则
3. **承诺要少，交付要多**：不要为了拿单过度承诺，上线时给惊喜

**推荐练习方法**：
- 每周练习一次"用 3 句话解释一个复杂概念"
