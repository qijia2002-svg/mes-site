### 学习目标

> SQL 是实施工程师最重要的技术能力。**不求你会设计数据库，但求你会查数据、验证数据、发现数据问题。**

### 必须掌握的 SQL 语句

**第一优先级（必须滚瓜烂熟）**：
```sql
SELECT 字段 FROM 表 WHERE 条件 ORDER BY 字段 DESC LIMIT N
SELECT * FROM 表 WHERE 字段 IN (值1, 值2)
SELECT 字段, COUNT(*) FROM 表 GROUP BY 字段 HAVING COUNT(*) > 1
SELECT a.字段, b.字段 FROM 表A a JOIN 表B b ON a.id = b.a_id
```

**第二优先级（会用就行）**：
```sql
INSERT INTO 表 (字段) VALUES (值)
UPDATE 表 SET 字段 = 值 WHERE 条件
DELETE FROM 表 WHERE 条件
```

**第三优先级（理解概念）**：
- 事务（BEGIN/COMMIT/ROLLBACK）
- 索引（知道什么是索引，为什么查询会变快）
- 表结构设计（主键/外键/字段类型）

### 练习方法

**推荐资源**：
1. **LeetCode 数据库题**（免费）：前 50 道 Easy-Medium 题，涵盖所有基础语法
2. **SQLZoo**（免费在线）：边学边练，不需要装数据库
3. **牛客网 SQL 专项练习**：按题型分类，针对性强

**练习场景（对应实施工程师真实工作）**：

场景1：验证 MES 工单数据
```sql
-- 查询今天创建的工单，按状态分组统计数量
SELECT status, COUNT(*) 
FROM mes_work_order 
WHERE DATE(created_at) = CURDATE()
GROUP BY status;
```

场景2：验证 BOM 数据一致性
```sql
-- 查询某个工单关联的物料明细（BOM展开）
