## SQL必须掌握的语法（按优先级）

### 第一优先级：SELECT 查询（滚瓜烂熟）

```sql
-- 基本查询
SELECT 字段 FROM 表 WHERE 条件

-- 条件查询
SELECT * FROM device_status WHERE status = ''OFFLINE''

-- 排序和限制
SELECT * FROM device_log ORDER BY create_time DESC LIMIT 10

-- 聚合统计
SELECT device_id, COUNT(*) as error_count
FROM device_log
WHERE error_type = ''timeout''
GROUP BY device_id
```

### 第二优先级：JOIN 关联查询（核心技能）

```sql
-- 内连接：两边都有的才保留
SELECT a.device_name, b.status
FROM devices a
JOIN device_status b ON a.id = b.device_id
WHERE b.factory = ''卷线一厂''

-- 左连接：以左表为主，右边没有的显示NULL
SELECT wo.order_no, pr.report_time
FROM mes_work_order wo
LEFT JOIN mes_production_report pr ON wo.id = pr.order_id
```

### 第三优先级：数据异常检测（最有用的实战技能）

```sql
-- 找重复数据
SELECT device_code, COUNT(*) as cnt
FROM devices
GROUP BY device_code
HAVING cnt > 1

-- 找缺失关联（工单没有报工记录）
SELECT wo.order_no
FROM mes_work_order wo
LEFT JOIN mes_production_report pr ON wo.id = pr.order_id
WHERE pr.id IS NULL
```

