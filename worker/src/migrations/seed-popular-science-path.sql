这一节，跟着一张真实订单走一遍。假设你是某工厂，客户发来一句话：

> 「我要 100 个这种铝合金外壳，下周五前送到。」

下面就是这张订单在工厂里的旅程。

## 第一站：接单（销售订单）

客户的话被记成一张「销售订单」，上面写着三件事：

- **要什么**：什么产品、什么规格；
- **要多少**：100 个；
- **何时要**：下周五（这叫「交期」）。

订单一进来，工厂的闹钟就开始响了——因为「交期」是硬 deadline。

## 第二站：排活（生产计划）

工厂不能来一单做一单，得统筹安排。计划员会看：哪条线有空？哪台设备能用？原料够不够？然后决定「这批活儿什么时候开始、排到哪条线」。

这一步产出的，是一张给车间的具体任务单，上面写清楚：做哪个产品、做多少个、走哪几道工序。

## 第三站：开工（工单 + 加工）

车间拿到任务单（工厂内部叫「工单」），就开始真正动手：

- 把材料搬到工位；
- 按工序一道道做（比如 切割 → 打孔 → 打磨 → 组装）；
- 每做完一道，就在系统里「报工」一下，告诉系统「这道我做完了、做了多少」。

「报工」听起来专业，其实就是汇报进度：今天做了 30 个、合格 29 个。

## 第四站：把关（质检）

做出来的活儿不能直接发走，得抽检：尺寸对不对、表面有没有瑕疵、功能好不好。

不合格的挑出来单独放，不能混进好货里。

## 第五站：入库与发货（完工 + 发出）

质检合格的产品，进仓库登记「做完了、入库了」，然后按交期打包发给客户。

到这一步，那张订单的旅程就走完了。

## 把这条线串起来记

```
客户要货（销售订单，带交期）
   ↓
工厂排活（生产计划 → 工单）
   ↓
车间加工（每道工序报工）
   ↓
质检把关（挑出不合格）
   ↓
入库发货（交给客户）
```

你只需要记住这条主干。后面碰到「工单」「报工」「交期」「完工数」这些词，回来对着这条线看，就知道它处在哪一站。

