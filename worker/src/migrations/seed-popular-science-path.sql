上一节我们跟着订单走了一圈，途中冒出几个词：工单、报工、交期、完工数。这一节把它们一个一个说成大白话。

你不用记英文缩写，先听懂「它在说什么」。

## 计划做多少：计划数量

工厂接到订单说「要 100 个」，系统就会定一个目标：**计划做 100 个**。

这是「打算做多少」，不是「真的做出来多少」。后面所有数字都围着它转。

## 真的做出来多少：完工数量

车间一边做一边报工，每报一次，系统就累加一次。最后累计出来的「实际做完并上报的数量」，就是**完工数量**。

打个比方：计划做 100 个，过程中坏了 5 个，实际只做出 95 个合格品——那完工数量就是 95。

> 记住一对最容易混的：计划数量说的是「打算」，完工数量说的是「实际交账」。两者不是一回事，差的那部分就是损耗或待补的。

## 什么时候要：交期

客户说的「下周五前送到」，在工厂里叫**交期**。

它是一条红线：计划、排产、催料，全是为了别越过这条线。交期准不准，是客户评价工厂靠不靠谱的头号指标。

## 出了事能不能查到：追溯

假设客户收到货，发现有一个是坏的。工厂能不能回答「这个坏的是哪天做的、哪台机器做的、谁做的、用的是哪批料」？

这种「顺藤摸瓜、从成品倒查到原料和设备」的能力，就叫**追溯**。

为什么重要？因为一旦出问题，能立刻定位是哪批料、哪台设备、哪个时段出的岔子，而不是整批召回瞎猜。

## 把它们放在订单旅程里看

回到上一节的五站：

- **接单**：定下「计划数量」和「交期」；
- **加工**：每道工序「报工」，一点点累出「完工数量」；
- **质检 / 发货**：用「追溯」兜底，万一出问题能查到根源。

```
计划数量（打算做）  ─┐
                     ├─→ 对照看：做没做够？有没有拖延？出问题能不能查？
完工数量（实际做）  ─┤
交期（何时要）      ─┤
追溯（能查根）      ─┘
```

## 检验一下

如果有人问你「工厂里老提的完工数、交期、追溯都是啥」，你能不能这样答：

> 「完工数是实际做出来的数量，计划数是打算做的；交期是客户要货的死线；追溯是出问题了能倒查到哪批料哪台机器。四个数字合起来，看工厂做没做够、拖没拖延、稳不稳定。」

