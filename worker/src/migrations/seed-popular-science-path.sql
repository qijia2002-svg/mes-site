## 工厂像一座不停运转的小城

把工厂想成一座小城，里面有几类「居民」，各管一摊：

- **接活的人**：客户说「我要 100 个这种零件」，他们把这句话记下来，这就是「订单」。
- **备料的人**：对照清单，把要做这件产品需要的材料、零件先找齐。
- **加工的人**：站在机器或工位前，把材料真正变成产品。
- **把关的人**：做完的活儿抽检一下，不好的挑出来。
- **发货的人**：把合格的产品打包、送走。

你不用记住这些岗位叫什么，只要记住一件事：**工厂的本质，是把「客户要的东西」变成「客户拿到手的东西」**。中间所有环节，都是为了让这件事不出错、不拖延。

## 工厂为什么需要「系统」

你可能会想：上面这些人，靠喊、靠纸、靠 Excel 也能干吧？

能，但容易乱。设想一下：

- 接活的人记错数量，车间多做了一倍；
- 备料的人少拿了一种零件，做到一半发现做不下去；
- 加工的人报了多少、合格多少，全靠本子记，月底对账对不上；
- 客户问「我的货到哪了」，没人能立刻答上来。

工厂一旦变大、订单一多，靠人脑和人本子就会漏。于是工厂引入一套电脑系统，把每个环节的数据都记下来、串起来——这就是后面会讲到的「MES」要干的事。

> 先别管 MES 是什么。这一节你只要记住：工厂是一连串「接活 → 备料 → 加工 → 把关 → 发货」的动作，系统是为了让这串动作不跑偏。

