## 班组

**定义**：为了完成某一工序任务而设立的**基层生产组织形式**

**组成**：一般由班组长和若干名操作工人组成

**示例**：焊接班组、组装班组、下料班组

## 工位

**定义**：车间生产环境中为完成特定生产任务或操作工序而划分的**具有特定空间和功能的工作位置**

**对应关系**：**一般一个工位对应一个操作工人**

## 流水线

**定义**：把生产过程分解为一系列简单、专门化的操作

**特征**：
- 每个操作由**特定工位或工人**负责
- 产品像在一条流动的线上一样，从一个工位依次流到下一个工位
- 经过各个工序加工处理，最终成为成品

## 产线

**定义**：**工厂管理者口中的模糊概念**

**可能指向**：可能指流水线，也可能是类似于流水线的工作台

**实际模式**：实际上**以离散型方式流转**

> 注意：客户讲的"物料"一般特指"下级配料"

## 对比速查表

| 概念 | 本质 | 数量关系 | 主要场景 |
|------|------|---------|---------|
| **班组** | 人员组织 | 一个班组 = 多名工人 | 人员管理 |
| **工位** | 物理位置 | 一个工位 ≈ 一个工人 | 工序执行 |
| **流水线** | 物理生产线 | 多个工位串联 | 连续生产 |
| **产线** | 业务称呼 | 可能指流水线或工作台 | 日常沟通 |

