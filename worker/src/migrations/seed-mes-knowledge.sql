## 批次管理

### 定义
将同一种产品按照一定的规则和标准划分为不同的批次，并对每个批次进行独立的标识、跟踪、记录和管理的过程。

### 核心原则
**按批生产、按批检验、按批追溯**

### 四大核心价值

| 价值 | 作用 |
|------|------|
| **质量追溯精准** | 出现质量问题时通过批次信息迅速追溯到生产时间、设备、原材料供应商、操作人员等，便于召回特定批次 |
| **质量改进有据** | 通过对不同批次产品质量数据的分析和对比，发现质量波动规律和潜在问题 |
| **生产进度跟踪** | 为生产计划和调度提供清晰的管理单元，实时跟踪各批次进度 |
| **成本核算准确** | 将原材料采购、生产加工、设备折旧、人工成本等各项费用准确地分摊到每个批次 |

### 批次流转卡字段
- 制单单号、产品图号、产品规格、订单号、批次号、数量、生产日期
- 物料清单明细（材料代码、名称、规格、材质、颜色、零件数、重量）
- 工序流转步骤（序号、工序名称、计划数量、完成数量、备注）

## SN 码管理

### 定义
利用 MES 系统对产品的**唯一序列号**进行全面管理。每个产品都被赋予一个独一无二的 SN，如同产品的"**身份证**"。

### 四大环节

```mermaid
graph LR
    A["1️⃣ 生成"] --> B["2️⃣ 工序监控"]
    B --> C["3️⃣ 质量关联"]
    C --> D["4️⃣ 售后追溯"]
```

#### 1. 生成规则
- 自定义性：MES 系统可根据企业需求自定义 SN 的生成规则
- 常见信息：产品型号、生产批次、生产日期、流水号等
- 示例：`ABC123 - 20241001 - 0001`（产品型号 - 生产日期 - 流水号）

#### 2. 工序流转监控
- 每经过一道工序，操作人员使用扫描设备读取产品的 SN
- 记录：开始时间、结束时间、操作人员、设备编号
- 实现对产品在生产线上流转过程的实时监控

#### 3. 质量数据关联
- 每个检验环节记录：检验结果（合格/不合格）、检验参数（尺寸、性能指标）、检验人员
- 出现质量问题时通过 SN 快速追溯生产过程和相关质量数据

#### 4. 质量追溯
- 售后出现质量问题时，通过 SN 追溯到产品的生产过程
- 追溯信息：原材料供应商、生产工艺参数等
- 帮助企业准确分析问题原因、采取针对性改进措施

## 批次 vs SN 码

| 维度 | 批次 | SN 码 |
|------|------|------|
| **标识对象** | 一批同规格产品（多个） | 单个产品（一物一码） |
| **追溯粒度** | 批次级 | 个体级 |
| **典型场景** | 原材料、半成品、过程品 | 成品、单件追溯需求强的产品 |
| **打印载体** | 批次流转卡 | SN 标签（条码/二维码） |
| **关联能力** | 同批次产品共享追溯信息 | 每个产品独立的全生命周期档案 |
| **实施成本** | 低 | 高 |

