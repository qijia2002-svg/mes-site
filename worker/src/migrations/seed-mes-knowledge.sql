## 层次码规则

| 层次码 | 含义 | 示例 |
|--------|------|------|
| `0` | 成品层（最顶层） | C 型按钮整体 |
| `0.1`、`0.2` | 一级子件 | 触点座、连接架 |
| `0.1.1`、`0.1.2` | 二级子件 | 静触点、动触点 |
| `0.1.1.1` | 三级子件 | ... |
| ... | 依此类推 | ... |

**编码逻辑**：父件编码 + `.` + 子件序号

## BOM 表关键字段

```
序号 | 层次 | 图号 | 名称及规格 | 材料 | 数量 | 单件重量(g) | 物料编号 | 备注
```

## 多层 vs 单层

| 维度 | 单层 BOM | 多层 BOM |
|------|---------|---------|
| **结构** | 只有一层 | 多层级嵌套 |
| **用途** | 配料表 | 工程设计、成本核算 |
| **优点** | 简单直观 | 反映真实装配关系 |
| **缺点** | 丢失层级信息 | 维护复杂 |

## 配套关系

```mermaid
