## 一句话理解
**MES = Manufacturing Execution System = 制造执行系统**，是面向制造企业车间执行层的生产数字化管理系统。

## 在企业信息化中的位置

```mermaid
graph LR
    ERP["🏢 ERP<br/>企业资源计划"] -->|下达订单| MES["⚙️ MES<br/>制造执行系统"]
    MES -->|工单指令| PLC["🔧 PLC<br/>底层控制"]
    PLC -->|实时数据| MES
    MES -->|报工数据| ERP
```

**层级关系**：MES 位于上层计划管理系统（ERP）与底层工业控制（PLC）之间的车间层管理信息系统。

## 起源

| 项目 | 内容 |
|------|------|
| 提出方 | 美国 AMR 公司（Advanced Manufacturing Research, Inc） |
| 时间 | 20 世纪 90 年代初 |

## 核心价值

```
ERP ─── 管"计划做什么"
MES ─── 管"怎么做、做了多少"
PLC ─── 管"设备怎么动"
```

MES 解决了"计划与执行之间的断层"，让车间真正实现：
- **透明化**：每件产品走到哪一步都看得见
- **可追溯**：出问题时能定位到工序、人员、设备
- **数字化**：人工记录 → 系统自动采集
- **实时化**：事后报表 → 实时看板

## 三层架构对比

| 层级 | 系统 | 关注点 | 典型问题 |
|------|------|--------|---------|
| 计划层 | ERP | 资源、订单、财务 | 卖什么、买什么、赚多少 |
| 执行层 | **MES** | 工序、人员、设备、质量 | 谁在做、做到哪、用什么做 |
| 控制层 | PLC / DCS / SCADA | 设备信号、参数 | 设备怎么动、参数对不对 |

