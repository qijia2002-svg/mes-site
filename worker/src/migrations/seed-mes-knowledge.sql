## 一句话理解
**BOM（Bill of Materials）= 物料清单 = 描述产品结构的"树状清单"。**

## BOM 层次码

```mermaid
graph TD
    L0["0<br/>C 型按钮（成品）"] --> L01["0.1<br/>C 型触点座 1NO+1NC"]
