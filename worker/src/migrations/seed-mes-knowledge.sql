## 1. 计件工资

**机制**：通过生产报工和检验，自动统计员工的生产数量，并依据预先设定的计件单价计算工资

**核心要素**：
- 自动统计生产数量（报工数据）
- 预设计件单价
- 自动计算工资

## 2. 阶梯工价

**定义**：根据不同的产量区间，并为每个区间制定相应的工价

**示例**：

| 工单数量区间 | 每件工价 |
|------------|---------|
| 0 ~ 100 件 | **5 元** |
| 101 ~ 200 件 | **4.5 元**（下降） |
| 201 ~ 300 件 | **4 元**（继续下降） |

**目的**：刺激工人主动接小批量的工单（避免大宗订单独占工价优势）

```mermaid
graph LR
    A["0-100 件<br/>5 元/件"] --> B["101-200 件<br/>4.5 元/件"]
    B --> C["201-300 件<br/>4 元/件"]
    A -.->|刺激小批量| D["工人主动接小单"]
```

## 3. 计次工资

**机制**：根据工单的报工次数来统计

**典型场景**：
- 模具上模、下模的次数
- 维修次数
- 其他难以直接计件的辅助型作业

## 4. 集体计件

**机制**：
```
集体完成的产品数量 × 计件单价 = 集体总工资
    ↓
按一定分配方式 → 集体中每个成员
```

**特点**：
- 成员往往负责不同工序
- 集体产出不易拆分到个人
- 需要二次分配（按工时 / 按岗位系数 / 按贡献度）

## 四种方式对比

| 维度 | 计件工资 | 阶梯工价 | 计次工资 | 集体计件 |
|------|---------|---------|---------|---------|
| **计量单位** | 产品数量 | 产品数量 | 工序次数 | 集体总产量 |
| **典型场景** | 直接生产工序 | 任务量波动大 | 辅助/维修类作业 | 流水线班组 |
| **激励效果** | 强（多劳多得） | 强（兼顾大小单） | 中 | 强（团队协作） |
| **细分到个人** | 直接 | 直接 | 直接 | 需二次分配 |
| **实施难度** | 低 | 中 | 低 | 中 |

