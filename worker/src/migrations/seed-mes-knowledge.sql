## 一句话理解
**MES 数据采集 = 从设备获取产量、状态、异常代码、工艺参数、性能参数、操作记录的过程。**

## 两种采集方式对比

```mermaid
graph TB
    subgraph "协议采集"
        P1["智能设备"] -->|Modbus/OPC UA/TCP/IP| M1["MES 系统"]
    end
    subgraph "IO 采集"
        P2["传感器/开关"] -->|电信号| IO["IO 接口"] --> M1
    end
```

## 协议采集

**方式**：通过特定通信协议与设备数据交互

**典型协议**：
- **Modbus**：工业领域最常用的串行通信协议
- **OPC UA**：跨平台工业通信标准
- **TCP/IP**：通用网络协议

**数据深度**（深层次）：
- 设备基本运行状态
- 设备参数设置
- 运行历史记录
- 故障代码

**示例**：智能电表的实时电量、电压、电流、功率因数等多项参数

## IO 采集

**方式**：基于硬件的输入输出接口采集

**原理链**：
```
外部物理量变化（温度/压力/开关状态）
    ↓
传感器产生电信号
    ↓
IO 接口转为数字信号
    ↓
MES 接收
```

**数据范围**（基本状态）：
- 开机/关机/运行/停止状态
- 数量
- 温度、压力、流量等模拟量信号
- 开关量信号

## 对比表

| 维度 | 协议采集 | IO 采集 |
|------|---------|--------|
| 数据深度 | **深层次**（内部参数、历史、故障） | **基本状态**（开/停/物理量） |
| 实施难度 | 需设备支持协议 | 需硬件接线 |
| 适用场景 | 智能设备 | 老旧设备 / 简单监测 |
| 数据量 | 大 | 小 |
| 成本 | 中 | 低 |

