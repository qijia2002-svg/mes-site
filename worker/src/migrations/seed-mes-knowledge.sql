## 追溯定义

### 什么是质量追溯
让企业清楚了解产品生产各个环节的详细信息。当产品出现质量问题时，可以通过追溯系统快速定位问题发生的环节、原因和责任人，采取有效的措施进行召回、整改和预防。

### 正向追溯

**定义**：从**原材料和零部件开始**，沿着生产流程的方向，追踪它们在整个生产过程中的流动和变化，直至形成最终产品

**目的**：记录每个环节的相关信息，以便在需要时能够清晰地了解产品的生产历史和质量情况

### 反向追溯

**定义**：从**最终产品出发**，沿着生产流程的反方向，追溯产品所使用的原材料、零部件，以及经过的生产工序、质量检验情况、操作人员等信息

**目的**：确定产品质量问题的根源或了解产品的详细生产历史

## 双轨制对比

| 维度 | 正向追溯 | 反向追溯 |
|------|---------|---------|
| **方向** | 原材料 → 零部件 → 半成品 → 成品 | 成品 → 半成品 → 零部件 → 原材料 |
| **典型场景** | 预测性质量管控、客户展示 | 售后质量问题调查、召回 |
| **溯源粒度** | 批次级（最常见） | 批次级 / SN 码级 |
| **触发频率** | 低（定期分析） | 高（出问题才用） |

