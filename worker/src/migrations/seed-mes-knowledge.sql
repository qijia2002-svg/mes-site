## 一句话理解
**稼动率 = 设备"真正干活"的时间占比，反映设备真实利用率。**

## 核心公式

```
设备稼动率 = 稼动时间 / 负荷时间 × 100%
```

## 时间分解

```mermaid
graph TB
    A["日历时间<br/>24h × N 天"] --> B["计划工作时间<br/>(如 8h/天)"]
    B --> C["负荷时间<br/>= 计划工时 - 计划停机"]
    C --> D["稼动时间<br/>= 负荷时间 - 停线时间"]
    D --> E["实际生产时间<br/>(生产良品)"]
    
    B -.->|扣除| F["计划停机<br/>(日常维护/检修/交接班)"]
    C -.->|扣除| G["停线时间<br/>(故障/换模/换线/等待物料)"]
```

## 概念详解

### 稼动时间

**定义**：指设备**实际生产的时间**，也就是设备真正用于**生产良品**的时间

**计算逻辑**：从负荷时间里扣除了设备的停线时间后剩余的时间

**停线时间包括**：
- 设备故障停机
- 换模换线
- 刀具更换
- 设备调整
- 等待物料等非生产时间

### 负荷时间

**定义**：指设备**可用于生产的时间**

**计算逻辑**：计划工作时间扣减设备计划停机时间后的时间

**计划停机时间包括**：
- 日常维护保养
- 计划性检修
- 交接班等

**示例**：企业规定设备每天计划工作 8 小时，但有 0.5 小时用于设备的日常维护保养，那么**负荷时间就是 7.5 小时**

### 加班时间是否包含？

**判断依据**：看客户需求，包含和不包含都可以

**注意**：如果不包含加班时间，则稼动率可能超过 100%

## 三类稼动率指标

```mermaid
graph LR
    A["时间开动率"] --> B["净开动率"]
    B --> C["设备时间利用率"]
```

| 指标 | 公式 | 含义 |
|------|------|------|
| **时间开动率** | 实际开机时间 / 计划开机时间 | 设备开了多久 |
| **净开动率** | 实际加工时间 / 计划开机时间 | 设备真正干活的时间占比 |
| **设备时间利用率** | 实际加工时间 / 负荷时间 | 净开动率扣除计划停机 |

## 稼动率与 OEE 的关系

```
OEE = 可用率 × 性能率 × 良品率
     = 时间开动率 × 净开动率 × 良品率
```

| OEE 维度 | 对应 MES 指标 |
|---------|--------------|
| **可用率（Availability）** | 时间开动率 |
| **性能率（Performance）** | 净开动率 |
| **良品率（Quality）** | 良品率 |

