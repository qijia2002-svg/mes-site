## 一句话理解
**工艺路线 = 产品从原材料到成品的完整加工流程说明书。**

## 定义

> 产品从原材料投入到成品产出的整个生产过程中，需要依次经过的各个工序、加工设备以及所采用的工艺方法和技术要求的**详细描述**。

**作用**：规定了产品生产的流程和顺序，是指导生产现场进行生产作业的重要依据。

## 五个核心要素

```mermaid
mindmap
  root((工艺路线))
    工序信息
      工序名称
    工序顺序
      先后执行顺序
    加工设备
      每道工序用啥
    工艺参数
      温度 压力 速度 时间
    技能要求
      操作证书 经验
```

## 五要素详解

| 要素 | 含义 | 示例 |
|------|------|------|
| **工序信息** | 产品生产需经过的每道工序名称 | 机械加工：车削/铣削/磨削；电子装配：贴片/焊接/测试 |
| **工序顺序** | 各工序之间的先后执行顺序 | 家具：木材切割→打磨→组装→上漆 |
| **加工设备** | 每道工序所使用的生产设备 | 数控车床、注塑机、自动化生产线 |
| **工艺参数** | 每道工序的具体工艺参数 | 加工温度、压力、速度、时间 |
| **作业人员技能要求** | 每道工序所需作业人员的技能水平和资质 | 操作证书、工作经验 |

## 多工艺路线

**定义**：在某些工厂中，存在一种产品，在不同情况下，采用不同的工艺路线

**应用场景**：同一产品根据规格/物料/订单差异走不同工艺

## 并行工序

**定义**：特殊情况下，两道工序可以同时进行，称为并行工序

```mermaid
graph LR
    A["工序 1"] --> B["工序 2-1"]
    A --> C["工序 3-1"]
    B --> D["工序 5"]
    C --> D
    D --> E["工序 6"]
```

**图示**：从工序 1 同时分支到工序 2-1、3-1，再汇合到工序 5、6

## 工序 vs 工步

| 维度 | 工序 | 工步 |
|------|------|------|
| **定义** | 独立的加工步骤 | 工序的组成部分 |
| **颗粒度** | 粗 | 细 |
| **执行** | 一般由一个工位或设备操作 | 在同一设备上用同一工具连续操作 |
| **示例** | 镗孔工序 | 粗镗 → 精镗 |

**示例**：汽车发动机缸体的"镗孔"工序，可能包括先用**粗镗刀**进行**粗镗**、再用**精镗刀**进行**精镗**等多个工步

## MES 数据模型

```sql
