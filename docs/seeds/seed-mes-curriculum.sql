## 一句话理解
**MES 上线失败最常见的原因不是系统不好用，是用户不会用**——培训做不好，系统再先进也是摆设。

## 正文

### 培训对象分层

| 角色 | 培训重点 | 培训时长 | 培训方式 |
|------|---------|---------|---------|
| 车间操作员 | 报工操作、异常上报 | 2-4 小时 | 实操演示 + 练习 |
| 班组长 | 产线监控、报表查看 | 2 小时 | 实操 + 场景练习 |
| 计划员 | 工单管理、调度操作 | 4 小时 | 实操 + 演练 |
| 系统管理员 | 配置管理、权限设置 | 8 小时 | 讲解 + 配置练习 |

### 培训设计原则

1. **分角色**：操作员和管理员的内容完全不同，不要"一刀切"
2. **重实操**：操作员培训中实操占比 ≥ 70%，少讲多练
3. **场景化**：用客户自己的产品数据做练习场景，而不是演示数据
4. **考核跟进**：培训后要有考核，确认操作员真的会用了

### 培训后持续支持
- 上线后第一周：实施顾问驻场，及时处理问题
- 上线后第一个月：建立微信群，快速响应
- 上线后三个月：回访收集改进建议

