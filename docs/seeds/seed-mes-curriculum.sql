'# 精益生产与 MES 的关系

## 一句话理解
**精益生产是理念，MES 是工具**。精益告诉你"为什么要减少浪费"，MES 帮你"看到浪费在哪里"。

## 正文

### 精益生产的核心理念
精益生产（Lean Production）的核心是消灭 7 大浪费（Muda）：
- 等待浪费（等料、等设备、等指令）
- 搬运浪费（物料来回搬动）
- 动作浪费（操作动作不高效）
- 加工浪费（不必要的加工步骤）
- 库存浪费（积压的原料/在制品/成品）
- 过度生产（生产超出需求）
- 缺陷浪费（次品、返工）

### MES 如何支撑精益

| 精益工具 | MES 支撑 |
|---------|---------|
| 看板管理 | MES 工单状态实时看板 |
| 拉动生产 | MES 按实际消耗触发补料 |
| 5S 管理 | MES 设备状态可视化 |
| OEE 计算 | MES 设备 OEE 自动统计 |
| 质量追溯 | MES 批次/序列号追溯 |
| 持续改善 | MES 数据支撑改善决策 |

### 关键理解
MES 不是精益生产的充分条件——上了 MES 不等于实现了精益。但没有 MES，精益的数据基础几乎不可能建立。

