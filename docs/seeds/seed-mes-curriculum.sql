'# MES 在企业信息化中的定位

## 一句话理解
**企业信息化像一个金字塔**：ERP 在计划层管"要做什么"，MES 在执行层管"怎么做到"，SCADA/PLC 在设备层管"实际做了没有"。MES 是中间那一层。

## 正文

### 企业信息化分层模型

| 层级 | 系统 | 核心问题 |
|------|------|---------|
| 计划层（L4） | ERP / SCM | 要生产什么？什么时候交付？ |
| 执行层（L3） | **MES / MOM** | 车间里怎么做？谁来做？ |
| 设备层（L2/L1） | SCADA / PLC | 设备在转吗？数据采集了吗？ |

### 关键理解：上下打通

**ERP → MES**：ERP 下达工单、物料清单（BOM）、生产计划
```
ERP："今天要生产 1000 台电机，优先级：高"
↓
MES 接收工单："收到，安排到 A 线 1 号产线"
```

**MES → ERP**：MES 回传生产实绩、完工数量、质量数据
```
MES："A 线已完成 800 台，良品率 98.5%，设备 OEE 85%"
↓
ERP 更新库存和财务数据
```

**MES → SCADA/PLC**：MES 下达工艺参数、采集指令
**SCADA/PLC → MES**：回传设备状态、传感器数据、报警信息

