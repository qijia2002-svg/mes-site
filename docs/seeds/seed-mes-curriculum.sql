'# MES 是什么

## 一句话理解
**MES = 制造执行系统**。它是工厂的"中枢神经"——把 ERP 的生产计划，在车间里真实执行出来，并实时反馈执行结果。

## 正文

### MES 的定义
MES 全称 **Manufacturing Execution System（制造执行系统）**，国际 MES 协会（MESA）定义为：在过程事件中优化生产活动的管理信息系统。

### MES 解决什么问题
没有 MES 的工厂：计划靠 Excel，生产靠打电话，出了问题靠追问。
有了 MES 的工厂：计划自动下达，工单实时跟踪，数据自动采集，异常及时报警。

### MES 的核心任务
- **连接**：把计划层（ERP）和设备层（SCADA/PLC）打通
- **执行**：把工单在车间里真正执行下去
- **透明**：让管理者实时看到生产进度
- **追溯**：每件产品能查到原料批次、生产时间、设备、操作员

