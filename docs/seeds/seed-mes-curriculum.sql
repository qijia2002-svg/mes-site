## 一句话理解
**OEE 是衡量设备效能的全球通用语言**——三个率相乘（可用率×性能率×良品率），告诉你"设备真正在干活的时间占比"。

## 正文

### OEE 计算公式

```
OEE = 可用率 × 性能率 × 良品率

可用率  = (计划运行时间 - 停机时间) / 计划运行时间
性能率  = 实际产量 / (理论产能 × 计划运行时间)
良品率  = 良品数量 / 实际产量
```

### OEE 损失来源

| 损失类型 | 示例 | 属于哪个率 |
|---------|------|----------|
| 设备故障 | 轴承损坏、电气故障 | 可用率 |
| 换模调整 | 换产品、换刀具 | 可用率 |
| 空转小停 | 缺料、等待指令 | 性能率 |
| 速度降低 | 参数设定低于理论速度 | 性能率 |
| 不良品 | 工艺参数漂移导致次品 | 良品率 |

**世界级 OEE 标准**：≥ 85%

### 设备台账数据
- 静态数据：设备编号、名称、型号、购置日期
- 动态数据：运行时间、停机时间、产量、维护记录

