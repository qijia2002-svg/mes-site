'# MES 8 大核心模块详解

## 一句话理解
**MES 的 8 大功能模块**，覆盖了从工单下达到数据采集的完整生产链条。实施工程师吃饭的本事，就在这 8 个模块里。

## 正文

### 模块 1：生产工单管理
MES 的核心驱动力。工单从哪里来（ERP 下达/手工创建），工单状态怎么流转（待排产→已排产→执行中→完成）。

### 模块 2：工序详细调度
把工单拆解到具体工序，决定每道工序在哪个工作中心、哪台设备、哪个班次做。

### 模块 3：生产单元分配
把资源（人、机、料）分配给具体的工单和工序，解决"谁来做、用什么做"的问题。

### 模块 4：过程管理
监控生产过程中的异常（设备故障、质量超限、物料短缺），及时报警和处理。

### 模块 5：物料跟踪
追踪物料在生产过程中的流转路径（来料→线边仓→工序→成品），支持批次追溯。

### 模块 6：设备管理
设备台账、运行状态、点检保养、故障记录、OEE 计算。

### 模块 7：质量管理
质检方案（首检/巡检/终检）、SPC 控制图、不良品处理流程、质量追溯。

### 模块 8：数据采集
采集设备运行数据（产量、停机时间、温度、压力），为其他模块提供数据基础。

## 现场对应
