'# 需求分析方法

## 一句话理解
**需求分析的核心是"问正确的问题"**——不是问客户想要什么功能，而是问他们现在遇到了什么问题、想要什么结果。

## 正文

### AS-IS → TO-BE 分析法

**AS-IS（现状流程）**：搞清楚现在是怎么做的
- 访谈车间操作员、计划员、车间主任
- 画出当前业务流程图
- 识别痛点：哪里效率低、哪里容易出错、哪里数据看不到

**TO-BE（目标流程）**：设计未来应该怎么做
- 基于 AS-IS 痛点，设计改进方案
- 与客户确认"改了之后达到什么效果"
- 将效果量化（时间缩短 X%、良率提升 Y%）

### 需求访谈的核心问题框架

| 维度 | 核心问题 | 目的 |
|------|---------|------|
| 现状 | 你们现在怎么知道今天产线干了多少活？ | 了解数据采集方式 |
| 痛点 | 最近一次质量问题是怎么发现的？多久？ | 识别追溯需求 |
| 期望 | 如果 MES 上线了，你最想先解决哪个问题？ | 确定优先级 |
| 约束 | 车间有多少台设备？有没有不能联网的？ | 评估实施难度 |
| 人员 | 操作员平均年龄？会用电脑吗？ | 评估培训难度 |

