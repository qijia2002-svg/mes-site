'# 追溯模型：正查与反查

## 一句话理解

> **追溯 = 沿批次或 SN 链路，从原料追踪到成品（或反向追查），把「谁在什么时候、用什么、做了什么」全部串起来。**

在 MES 系统中，追溯不是一张表，而是一整条**数据链路**。有了这条链路，一旦某个环节出问题，你才能像查快递一样，一层层找到源头或扩散到影响范围。

