## 断链的常见位置

理解了四张表之后，断链的原因就非常清晰了。以下是现场实施中最常见的四种断链场景：

| 断链位置 | 现象 | 根因 |
|---------|------|------|
| **原料未绑定批次** | 报工记录中 material_batch 为空 | 来料入库时未登记批次号 |
| **报工未录批次** | 装配报工有 SN，但原料批次字段为空 | 报工界面批次字段非必填 |
| **批次已出库** | 能查到批次记录，但报工里找不到关联 | 批次出库后数据未同步 |
| **SN 未生成** | 工单有报工记录，但没有 SN | SN 生成时机过早或过晚 |

