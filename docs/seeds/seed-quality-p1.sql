## 面试能讲

面试时聊到数据表设计，经常会被问到：「追溯系统实施时，最大的坑是什么？」

答案是：**源头数据录入率**。

很多企业的追溯系统设计得很完美，四张表齐全，JOIN 关系清晰，但上线后发现数据全是空的。根因不在技术，在流程：

- **报工是选填的**：工人觉得麻烦，跳过报工
- **批次是手写的**：批次号靠人工输入，容易填错或漏填
- **SN 是后来补录的**：生产时没扫码，包装时手动补录，导致 SN 和报工对不上

所以在现场实施时，**数据录入率和数据准确性**比表结构设计更难解决。实施顾问 70% 的时间都在处理数据补录和流程改造，而不是写 SQL。

