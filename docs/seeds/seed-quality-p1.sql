## 面试能讲

面试时聊到追溯，最容易被问到：「追溯系统上线最大的难点是什么？」

标准答案只有一个：**源头数据录入率**。

不是系统设计，不是数据库性能，而是车间工人愿不愿意填、会不会填、填的对不对。

很多企业上了 MES 之后，追溯链路看起来很完整，但真正追溯时发现数据全是空的——因为报工是选填的，批次是手动输入的，没人愿意多花那 30 秒。

所以在现场实施时，追溯系统的核心不是技术架构，而是**流程强制性和数据校验规则**：

- 关键工序报工必填，批次字段不能为空
- SN 在关键工位自动生成，不依赖人工输入
- 报工数据与实际产出数量自动核对，超出容差立即报警

