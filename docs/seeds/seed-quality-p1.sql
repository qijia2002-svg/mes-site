## 正查与反查：两种追溯方向

### 正向追溯（Forward Trace）

**路径：原料 → 工序 → 半成品 → 成品**

从最早端的物料出发，跟踪它最终流向了哪些成品、哪些批次。典型应用场景：

- **供应商物料出现质量问题**，需要召回所有使用了该批次原料的成品
- **法规要求**（如汽车 IATF 16949、食品 FDA 21 CFR Part 11）必须能提供正向追溯链
- **审计核查**：证明原材料来源合规、流向可查

### 反向追溯（Backward Trace）

**路径：成品 → 工序 → 半成品 → 原料**

从具体某台成品或某个批次出发，逆向还原它的生产过程。典型应用场景：

- **客户投诉某台产品异常**，需要定位是哪批原料、哪个班次、哪个工位出的问题
- **批次异常调查**：发现某批半成品不良，追溯上游原料和工艺参数
- **质量门禁判断**：某成品检出不良，反查该工单是否还有其他受影响产品

### 批次追溯 vs SN 追溯

| 维度 | 批次追溯 | SN 追溯 |
|------|---------|--------|
| 适用场景 | 流程制造（化工、食品、药品） | 离散装配（电子、汽车零部件） |
| 粒度 | 同批次产品共享同一追溯链 | 每台产品独立追溯链 |
| 优势 | 数据量小，管理简单 | 精度高，可定位到单台 |
| 劣势 | 颗粒度粗，影响范围可能过大 | 数据量大，SN 生成和管理成本高 |

