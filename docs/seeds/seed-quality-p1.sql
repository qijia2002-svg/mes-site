## 一句话理解

> **追溯链路靠四张核心表撑起来：报工表记录「谁干了什么」，批次表记录「原料从哪来」，SN 表记录「产品是谁」，工序表记录「标准怎么走」。**

这四张表之间的关系，就是追溯系统的骨架。理解表结构，比背 SQL 语法更重要。

---

## 四张核心表速览

### 1. 报工表（work_report）

记录每道工序的实际生产数据，是追溯链路的主干线。

```sql
-- 报工表结构（核心字段）
work_report
├── id               -- 主键
├── work_order_id    -- 工单ID（追溯的时间窗口）
├── process_step_id  -- 工序ID（追溯的节点）
├── product_sn       -- 产品SN（离散装配核心）
├── material_batch   -- 原料批次（批次追溯核心）
├── operator_id      -- 操作员（定位责任人）
├── report_time      -- 报工时间
├── quantity         -- 报工数量
├── status           -- 报工状态
└── ...其他扩展字段
```

报工表是追溯的**中枢**——它同时关联了 SN 和批次，也记录了工序和工单。所有追溯查询几乎都要 JOIN 这张表。

### 2. 批次表（material_batch）

记录原材料/半成品的批次信息，是正向追溯（原料→成品）的起点。

```sql
-- 批次表结构（核心字段）
material_batch
├── id               -- 批次ID
├── material_code    -- 物料编码
├── supplier_id      -- 供应商ID（召回时用）
├── batch_no         -- 批次号
├── produce_date     -- 生产日期
├── expire_date      -- 有效期（判断是否在追溯范围内）
├── quantity         -- 批次数量
├── warehouse_id     -- 当前仓库
└── status           -- 批次状态（可用/冻结/已用尽）
```

批次表的核心作用是**定位原料来源**。质量异常时，通过批次号可以查到供应商、进货时间、检验记录。

### 3. SN 表（product_sn）

记录每个独立产品的序列号，是离散装配追溯的基础。

```sql
-- SN表结构（核心字段）
product_sn
├── id               -- 主键
├── sn               -- 序列号（全局唯一）
├── product_code     -- 产品型号
├── work_order_id    -- 所属工单
├── line_id          -- 产线ID（定位生产地点）
├── shift_id         -- 班次ID（定位生产时间）
├── create_time      -- SN生成时间
├── status           -- SN状态（正常/报废/返修）
└── ...关联产品信息
```

SN 表的关键是**全局唯一性**和**生成时机**。SN 必须在关键工位自动生成，禁止人工输入，且同一 SN 不能重复使用。

### 4. 工序表（process_step）

定义生产流程中的标准工序，是追溯链路的节点定义。

```sql
-- 工序表结构（核心字段）
process_step
├── id               -- 工序ID
├── process_name     -- 工序名称
├── process_code     -- 工序编码
├── is_trace_required -- 是否必填报工（追溯关键节点）
├── is_sn_required   -- 是否需要生成/绑定SN
├── sequence         -- 工序顺序
├── ...其他配置
```

工序表中 **`is_trace_required`** 字段是追溯质量的分水岭：设为必填的工序，如果跳过报工，追溯链路就会断在此处。

