│                    追溯链路数据流向                                │
├─────────────────────────────────────────────────────────────────┤
│                                                                 │
│  [供应商批次] ──→ [来料报工] ──→ [装配工序报工]                  │
│       │                │                  │                     │
│       ↓                ↓                  ↓                     │
│  material_batch   work_report       work_report                 │
│  (批次来源)        (来料入库)         (原料+SN关联)               │
│                                              │                   │
│                                              ↓                   │
│                              [半成品 SN] ←── work_report         │
│                                   │                             │
│                                   ↓                             │
│                              product_sn (SN 生成)               │
│                                   │                             │
│                                   ↓                             │
│  [成品出库] ←── [包装工序报工] ←── [功能测试报工] ←── ...         │
│                    ↑                  ↑                          │
│               work_report         work_report                    │
│                                                                 │
└─────────────────────────────────────────────────────────────────┘
```

**核心 JOIN 逻辑：**

```sql
-- 完整追溯链路：成品 SN → 原料批次
SELECT
    sn.sn,
    sn.product_code,
    wr.process_step_id,
    wr.operator_id,
    wr.report_time,
    mb.batch_no,
    mb.supplier_id,
    mb.produce_date
FROM product_sn sn
JOIN work_report wr ON sn.sn = wr.product_sn
LEFT JOIN material_batch mb ON wr.material_batch = mb.batch_no
WHERE sn.sn = '';   -- 填入目标 SN
```

