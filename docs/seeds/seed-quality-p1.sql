## 方法三：日期边界法

### 原理

追溯有明确的时间窗口：批次有有效期，工单有计划时间，报工有实际时间。如果追溯范围超出了数据记录的时间边界，自然查不到结果。

### 常见边界问题

| 边界类型 | 问题表现 | 排查方法 |
|---------|---------|---------|
| **批次有效期** | 原料批次已过期，系统中被标记为冻结 | 检查 material_batch.expire_date |
| **工单时间窗口** | 追溯的 SN 属于历史工单，报工数据已归档 | 检查 work_report 是否有归档表 |
| **数据保留策略** | 超过 6 个月的数据被定期清理 | 确认数据保留周期和归档策略 |
| **系统切换期** | 旧系统数据未迁移到 MES | 对比新旧系统数据完整性 |

### SQL 实战

```sql
-- 检查目标批次是否在有效期内
SELECT
    mb.batch_no,
    mb.expire_date,
    mb.status,
    CASE
        WHEN mb.expire_date < date('now') THEN '已过期'
        WHEN mb.expire_date < date('now', '+30 days') THEN '30天内到期'
        ELSE '正常'
    END AS health_status
FROM material_batch mb
WHERE mb.batch_no = '';  -- 填入目标批次号

-- 检查报工数据的时间范围
SELECT
    MIN(report_time) AS earliest_report,
    MAX(report_time) AS latest_report,
    COUNT(DISTINCT DATE(report_time)) AS working_days
FROM work_report;
```

