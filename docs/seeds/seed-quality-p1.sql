## 奥来电器场景：断路器装配的追溯实践

以奥来电器的断路器装配为例，理解实际生产中的追溯结构：

**产品特征：**
- 每台断路器有唯一 **SN（序列号）**，贴在外壳上
- 关键外购件（触点、弹簧、绝缘件）按**批次**管理
- 装配经过 6 道工序：来料检验 → 零件组装 → 耐压测试 → 功能测试 → 包装 → 出库

**追溯链路设计：**

```
外购件批次（触点批次 #20260101）
  → 来料报工记录（批次绑定）
  → 装配工序报工（关联来料批次 + 本工序操作员）
  → 半成品 SN（在耐压测试工位生成）
  → 成品 SN（在包装工位生成）
  → 成品出库记录（关联客户/订单）
```

这条链路中，**任何一环断掉，追溯就断了**。比如来料报工没绑定批次，或者耐压测试工位跳过了报工，整条链就变成了「黑洞」。

