## 根因归类：断链的五大类型

通过上述三种方法定位到断点后，需要对根因进行归类，才能从根本上解决问题：

| 根因类型 | 描述 | 典型场景 | 处置方向 |
|---------|------|---------|---------|
| **数据未录** | 实际生产发生了，但数据没有录入系统 | 工人跳过报工、批次忘填 | 流程强制化、培训、扫码自动化 |
| **系统限制** | MES 系统本身不支持某些操作 | SN 生成时机过早、无法补录 | 系统功能改造、二次开发 |
