## 一句话理解

> **断链定位的本质是「数量对比 + 缺失检测」：先数清楚每层应该有多少条记录，再找出哪一层少了、少了谁。**

追溯链路就像一条流水线，每个环节都要有数据通过。如果某个环节的数据量突然变少或变空，说明追溯在这里断了。排查断链的核心工具就是 SQL 的 COUNT 和 IS NULL。

---

## 方法一：逐层 COUNT 对比法

### 原理

追溯链路每经过一个环节，数据量理论上应该保持一致（或按良率递减）。如果某层数据量突然大幅减少，说明这一层有数据缺失。

### 典型场景分析

```
成品 SN 总数（product_sn）:  1000 条
  ↓ 有报工记录的 SN 数:        985 条   ← 少了 15 条，说明 15 台没报工
  ↓ 有批次信息的报工数:        920 条   ← 少了 65 条，说明 65 条报工没绑定批次
  ↓ 有供应商信息的批次:        900 条   ← 少了 20 条，说明 20 批原料没登记供应商
```

### SQL 实战

```sql
-- Step 1：统计成品 SN 总数
SELECT COUNT(*) AS total_sn FROM product_sn;

-- Step 2：有报工记录的 SN 数（内层有报工就算）
SELECT COUNT(DISTINCT sn.product_sn) AS sn_with_report
FROM product_sn sn
INNER JOIN work_report wr ON sn.sn = wr.product_sn;

-- Step 3：有原料批次信息的报工数
SELECT COUNT(*) AS report_with_batch
FROM work_report
WHERE material_batch IS NOT NULL AND material_batch != '';
```

执行顺序：先看 Step1 和 Step2 的差距，定位「哪台 SN 没报工」；再看 Step2 和 Step3 的差距，定位「哪条报工没绑批次」。

