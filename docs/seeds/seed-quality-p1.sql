## 影响范围评估的量化方法

影响范围评估是追溯报告中最关键的商业决策依据。以下是量化评估的 SQL 方法：

```sql
-- 评估某批次原料影响了多少成品
SELECT
    mb.batch_no,
    mb.material_code,
    COUNT(DISTINCT wr.product_sn) AS affected_products,
    COUNT(DISTINCT wr.work_order_id) AS affected_orders
FROM material_batch mb
JOIN work_report wr ON mb.batch_no = wr.material_batch
WHERE mb.batch_no = ''  -- 填入目标批次
GROUP BY mb.batch_no, mb.material_code;
