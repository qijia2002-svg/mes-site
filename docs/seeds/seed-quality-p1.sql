## 追溯在国际标准中的位置

追溯能力归属 **ISA-95 五层模型** 的 **L3 执行层**（MOM/MES 层）。L1/L2 负责设备和工艺控制，L3 负责生产执行与数据采集，而追溯数据正是 L3 层的核心产出之一：

| 层级 | 名称 | 与追溯的关系 |
|------|------|-------------|
| L1/L2 | 设备控制层 | 采集工艺参数，生成追溯基础数据 |
| **L3** | **生产执行层** | **记录报工、批次、SN，构建追溯链路** |
| L4 | 生产计划层 | 下达工单，决定追溯的时间窗口 |
| L5 | 企业层 | 查询追溯报告，支持召回决策 |

这意味着：**追溯系统的数据质量，取决于 L3 层的报工数据录入率**。设备层数据再完整，报工漏填、批次忘绑，一切追溯都是空谈。

