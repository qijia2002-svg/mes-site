## 方法二：IS NULL 判断法

### 原理

断链的直接证据是**关键字段为空**。用 `LEFT JOIN ... WHERE target IS NULL` 可以精准定位每层断掉的记录。

### 场景 1：报工未绑定原料批次

```sql
-- 找出所有报工中原料批次字段为空的记录
SELECT
    wr.id,
    wr.work_order_id,
    wr.process_step_id,
    wr.product_sn,
    wr.report_time
FROM work_report wr
WHERE wr.material_batch IS NULL OR wr.material_batch = '';
```

### 场景 2：SN 未生成报工记录

```sql
-- 找出所有 SN 中没有报工记录的
SELECT sn.sn, sn.product_code, sn.create_time
FROM product_sn sn
LEFT JOIN work_report wr ON sn.sn = wr.product_sn
WHERE wr.id IS NULL;
```

### 场景 3：批次未登记供应商

```sql
-- 找出所有批次中供应商字段为空的
SELECT mb.batch_no, mb.material_code, mb.quantity
FROM material_batch mb
WHERE mb.supplier_id IS NULL OR mb.supplier_id = '';
```

### 面试能讲

面试时如果被问到「如何快速定位追溯断链」，可以回答：

> 「我会先从端点出发，正向和反向同时 COUNT 对比。比如从成品 SN 出发，看有多少 SN 关联到了报工记录，再看报工记录里有多少绑定了原料批次。每跳一层都做一次数量对比，数量突然减少的那一层，就是断链发生的位置。然后再用 IS NULL 精确找到具体是哪些记录断了。」

